import { expect, test } from '@playwright/test'

test('the same network and canvas transform into a globe and reverse on scroll', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/')
  const scene = page.locator('[data-marketing-scene]')
  const renderer = page.locator('[data-marketing-three]')
  // This test deliberately requires WebGL; fallback is tested independently.
  await expect(scene).toHaveAttribute('data-hero-renderer', 'ready')
  const canvas = await renderer.locator('canvas').elementHandle()
  const nodes = await renderer.getAttribute('data-node-count')
  const edges = await renderer.getAttribute('data-edge-count')
  expect(Number(nodes)).toBeGreaterThan(1000)
  expect(Number(edges)).toBeGreaterThan(100)
  await expect.poll(async () => Number(await renderer.getAttribute('data-morph-progress'))).toBeLessThan(0.001)
  const globeTop = await page.locator('[data-globe-chapter]').evaluate((el) => el.getBoundingClientRect().top + window.scrollY)
  await page.evaluate((top) => window.scrollTo({ top, behavior: 'instant' }), globeTop)
  await expect.poll(async () => Number(await renderer.getAttribute('data-morph-progress'))).toBeGreaterThan(0.999)
  await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }))
  await expect.poll(async () => Number(await renderer.getAttribute('data-morph-progress'))).toBeLessThan(0.001)
  expect(await canvas.evaluate((el) => el === document.querySelector('[data-marketing-three] canvas'))).toBe(true)
  await expect(renderer).toHaveAttribute('data-node-count', nodes)
  await expect(renderer).toHaveAttribute('data-edge-count', edges)
})

test('connections grow after globe completion while the stage stays visible and reverse on scroll', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/')
  await expect(page.locator('[data-marketing-scene]')).toHaveAttribute('data-hero-renderer', 'ready')
  const renderer = page.locator('[data-marketing-three]')
  const canvas = await renderer.locator('canvas').elementHandle()
  const globeTop = await page.locator('[data-globe-chapter]').evaluate((el) => el.getBoundingClientRect().top + window.scrollY)
  const scroll = (offset) => page.evaluate((top) => window.scrollTo({ top, behavior: 'instant' }), globeTop + offset)
  await scroll(0)
  await expect.poll(async () => Number(await renderer.getAttribute('data-morph-progress'))).toBeGreaterThan(0.999)
  await expect.poll(async () => Number(await renderer.getAttribute('data-network-progress'))).toBeLessThan(0.001)
  await scroll(750)
  await expect.poll(async () => Number(await renderer.getAttribute('data-network-progress'))).toBeGreaterThan(0.45)
  await expect.poll(async () => Number(await renderer.getAttribute('data-network-progress'))).toBeLessThan(0.6)
  expect(Math.abs(await page.locator('.planetary-chapter__stage').evaluate((el) => el.getBoundingClientRect().top))).toBeLessThan(2)
  await scroll(1400)
  await expect.poll(async () => Number(await renderer.getAttribute('data-network-progress'))).toBeGreaterThan(0.999)
  await expect(page.locator('[data-network-status]')).toHaveText('A planetary network taking shape')
  await scroll(0)
  await expect.poll(async () => Number(await renderer.getAttribute('data-network-progress'))).toBeLessThan(0.001)
  expect(await canvas.evaluate((el) => el === document.querySelector('[data-marketing-three] canvas'))).toBe(true)
})

test('globe controls rotate and zoom without stopping page scrolling', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/')
  await expect(page.locator('[data-marketing-scene]')).toHaveAttribute('data-hero-renderer', 'ready')
  await page.locator('[data-globe-chapter]').scrollIntoViewIfNeeded()
  const renderer = page.locator('[data-marketing-three]')
  await page.getByRole('button', { name: 'Rotate globe right' }).click()
  await expect.poll(async () => Number(await renderer.getAttribute('data-globe-yaw'))).toBeGreaterThan(0)
  await page.getByRole('button', { name: 'Zoom in', exact: true }).click()
  await expect.poll(async () => Number(await renderer.getAttribute('data-globe-zoom'))).toBeGreaterThan(1)
  await page.getByRole('button', { name: 'Pause globe motion' }).click()
  await expect(page.getByRole('button', { name: 'Resume globe motion' })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Reset globe view' }).click()
  await expect.poll(async () => Number(await renderer.getAttribute('data-globe-zoom'))).toBe(1)
  const before = await page.evaluate(() => window.scrollY)
  await page.mouse.wheel(0, 400)
  await expect.poll(() => page.evaluate(() => window.scrollY)).toBeGreaterThan(before)
})

test('reduced motion retains the planetary composition without WebGL or hidden controls', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  const requested = []
  page.on('request', (request) => requested.push(request.url()))
  await page.goto('/')
  await expect(page.locator('[data-marketing-scene]')).toHaveAttribute('data-hero-renderer', 'fallback')
  await expect(page.locator('[data-marketing-three] canvas')).toHaveCount(0)
  await expect(page.locator('.globe-static-orb')).toBeAttached()
  await expect(page.getByRole('button', { name: 'Zoom in', exact: true })).toHaveCount(0)
  expect(requested.some((url) => url.includes('three-marketing'))).toBe(false)
})
